import AppCore

/// 棱镜：**饱和度拉满、玻璃最薄**的那一档，走的是最主流的那套**科幻蓝**：
/// 近黑深蓝打底（色相 255，深色外观 L 0.172），主操作是一块电光青。
///
/// 另外四套（莫兰迪 / 雾青 / 素白 / 霜白）走的是「降饱和 = 降噪」那条路，
/// 星云在此之上把响度调了一档。**这套是这条线的另一端**：
/// 三团高饱和光晕（青 195 → 电蓝 262 → 靛紫 285，冷色那半边的一整段光谱）
/// 透过全应用最薄的一层薄膜，边缘是一圈泛青的发丝线 ——
/// HUD / 全息那套语汇里该有的东西，
/// 这里一件不缺，而且**全部落在既有的三层结构里**（薄膜 / 边缘 / 投影），
/// 没有为它新开一套画法。
///
/// ## 一块「响」的主按钮怎么还能有 7:1
///
/// 鲜艳和可读在实心按钮上是**直接打架**的：7:1 要求填充要么很亮（配近黑字），
/// 要么很深（配近白字），而「鲜艳」的直觉答案恰恰是中间调 —— 一块 L 0.64 的
/// 饱和色配白字只有 3.7:1，配黑字也不到 4，两头不靠。
///
/// 第一版走的是**深**的那一头：L 0.460 / chroma 0.205 的深紫配白字，裸算 7.9:1，
/// 数字很漂亮。**然后它和这套自己的斜光打起来了** —— 26% 的白洗上去，
/// 白字掉到 6.7:1，而且再怎么压深也救不回来（L 0.30 时仍然只有 6.7）。
/// 道理很直白：**斜光是「光」，光该落在亮的填充上。** 一块深底按钮顶着一道白光，
/// 本来就是自相矛盾的画法。
///
/// 所以填充翻回**亮**的那一头：`accentFill` 是 L 0.790 / chroma 0.121 的电光青。
/// **青正好是少数几个「越亮越浓」的色相之一** —— L 0.62 时它最多只有 0.106，
/// 到 L 0.86 反而能到 0.147（蓝在同一段是反的：L 0.62 能到 0.175，
/// L 0.86 只剩 0.072）。所以「亮填充 + 近黑字」这条对青特别友好，
/// 换成蓝就得在饱和度上大让一步。
///
/// **鲜艳没有让步，让步的是「深色按钮」那个直觉。**
///
/// 浅深两种外观用的是同一块填充色：它在近白的底上和在近黑的深蓝上都跳得出来，
/// 不需要各配一套。
///
/// ## 色域比色相表更早说话
///
/// sRGB 的色域在蓝紫（265）最宽，在青绿最窄，而且**大部分色相越亮越窄**。
/// 所以这套的浅色光晕只能是粉彩档（L 0.85 的蓝最多 chroma 0.072），
/// 深色那档才吃得下 0.20 以上 —— 浅色外观下它像一块被阳光照透的玻璃，
/// 深色外观下才是 HUD。这不是两种设计，是同一套色在两种亮度下能到的极限。
///
/// 主按钮那道渐变也是被这条定的：青 202 → 电蓝 245，**只跨 43 度**。
/// 再往蓝里走十几度，那一端就得压暗才保得住饱和度，两端的亮度差就过线了
/// （`accentGradientKeepsOneBrightness` 卡在 1.25）。宁可跨度短一点、
/// 两端都够浓 —— 一道「浓 → 灰」的渐变看着不是渐变，是没调匀。
///
/// | 角色 | 色相 | 是什么 |
/// |---|---|---|
/// | `accent` | 202 | 电光青。主操作、当前选中、拖放落点 |
/// | `info` | 265 | 蓝。信息态 —— 离青 63 度，和 accent 分得开 |
/// | `success` | 145 | 绿。离 accent 57 度 —— 「选中」和「做完了」得一眼分得开 |
/// | `danger` | 20 | 红。全屏唯一的暖色，也是唯一跳出这段光谱的颜色 |
/// | 星球 | 235 / 262 / 285 | 青蓝能量环 → 电蓝球体 → 靛紫外晕 |
/// | 网格 | **无** —— 那是星云的签名，这套靠能量星球给玻璃东西可折射 |
extension Palette {
    static let prism = Palette(.prism) { tint in
        // 图标色相：这套底本身就有颜色，所以彩色图标反而要**离光晕远一点**，
        // 不然侧边栏的图标看着像是被底下那团光染出来的。
        switch tint {
        case .neutral: 255    // 蓝灰，等于不上色
        case .warm: 70        // 金
        case .rose: 10        // 玫瑰
        case .violet: 305     // 紫
        case .blue: 265       // 蓝
        case .teal: 195       // 青
        case .green: 145      // 绿
        case .indigo: 285     // 靛
        case .plum: 330       // 莓
        case .lime: 120       // 苔
        }
    } lookup: { token in
        switch token {

        /// 左上的镜面高光。**它不进对比度合成链** —— 1px 的边不会压在正文底下，
        /// 所以它可以比任何一个面都亮。玻璃的厚度全靠它。
        case .rimSpecular: Ramp(
            light: OKLCH(1.000, 0.000, 0, alpha: 0.85), dark: OKLCH(1.000, 0.000, 0, alpha: 0.62)
        )
        /// 右下的色散边。有厚度的玻璃会分光：一条边偏冷白，另一条偏主题自己的色。
        case .rimDispersion: Ramp(
            light: OKLCH(0.700, 0.130, 202, alpha: 0.38), dark: OKLCH(0.820, 0.145, 202, alpha: 0.60)
        )

        // MARK: 读写面
        /// 正文躺着的那块地：代码框、结果区、长文本。
        ///
        /// **它是唯一一块不上玻璃的表面**，而且必须不上 —— 玻璃会折射背后的
        /// 星球，一段等宽代码压在一片会动的折射上是读不下去的。
        /// 玻璃管的是 chrome 和控件，这一块管的是「拿来读、拿来改」的东西。
        case .well: Ramp(
            light: OKLCH(0.940, 0.014, 255), dark: OKLCH(0.175, 0.010, 255),
            lightHC: OKLCH(0.955, 0.004, 255), darkHC: OKLCH(0.170, 0.006, 255)
        )

        // MARK: 氛围底与光晕
        /// 深色那档的 chroma 是 0.042 —— L 0.172 上蓝的色域上限就在 0.048 附近。
        /// **主题色的存在感主要在这一层**：一块按钮上的渐变只占一屏的百分之几，
        /// 而这层底铺满整个窗口。「科幻蓝」读不读得出来，先看它蓝不蓝。
        case .backdrop: Ramp(
            light: OKLCH(0.970, 0.006, 255), dark: OKLCH(0.180, 0.032, 259),
            lightHC: OKLCH(0.975, 0.004, 255), darkHC: OKLCH(0.128, 0.008, 255)
        )
        /// 能量环。**深色那档换了一笔交易：拿透明度换明度。**
        ///
        /// 第一版是 L 0.745 / alpha 0.175 的中明度蓝，出图之后环读成一条灰线 ——
        /// 「电光」要的是看得出它在**发光**，不是看得出它在那儿。
        ///
        /// 直觉的修法是把 alpha 拉上去，但那条路是封死的：这颗星球压在整扇窗口
        /// 底下，前景每一块半透明面板都要从它上面经过，亮度带一抬，压在面板上的
        /// 正文当场掉线（试过 alpha 0.34，`inkTertiary` 从 4.65 掉到 2.38）。
        ///
        /// 所以换成**同样的亮度预算，花在明度上而不是浓度上**：
        /// L 0.900 / chroma 0.095 / alpha 0.135。合成出来的亮度比第一版还低一点点
        /// （正文最差格从 5.17 升到 4.95），但那条线本身是**近白**的 ——
        /// 而近白正是发光体该有的样子：光源的核心总是往白里跑，颜色留给它周围
        /// 那圈光晕（`auraDeep`）去承担。色相跟着 accent 挪到 205，
        /// 环和主按钮因此是同一段光谱的两头。
        ///
        /// 浅色那档一个数没动 —— 它同样贴着上限（body 4.90），
        /// 而且近白的底上「更亮」根本不是个方向。
        case .auraLead: Ramp(
            light: OKLCH(0.870, 0.078, 195, alpha: 0.28),
            dark: OKLCH(0.900, 0.095, 205, alpha: 0.122),
            lightHC: OKLCH(0.870, 0.078, 195, alpha: 0),
            darkHC: OKLCH(0.900, 0.095, 205, alpha: 0)
        )
        /// 暗球体与球面边缘光：电蓝。和能量环是**邻近色**，不是两种颜色在对撞。
        /// 蓝紫（258）是 sRGB 色域最宽的一段，所以球心还留得住颜色。
        ///
        /// 这一层是整颗星球里唯一会被**大面积**正文压住的（球体是个实心圆），
        /// 所以 `AuroraOrb.sphere` 把圆心垫的是氛围底、只在贴近边缘处才给到 0.62 ——
        /// 亮的部分全部收在环和边缘光那两条细线上。细线不挡字。
        case .auraTrail: Ramp(
            light: OKLCH(0.850, 0.050, 262, alpha: 0.26),
            dark: OKLCH(0.555, 0.125, 258, alpha: 0.166),
            lightHC: OKLCH(0.850, 0.050, 262, alpha: 0),
            darkHC: OKLCH(0.555, 0.040, 259, alpha: 0)
        )
        /// 外晕：靛紫。光谱的另一端，也是星球铺得最开的一层。
        /// **颜色主要由它承担** —— 环已经跑去近白了，一颗只有白线没有色的星球
        /// 是张线框图。峰值压在能量环所在的半径上，所以它读起来是
        /// 「环在往外漏光」，不是「中间有一团雾」。
        case .auraDeep: Ramp(
            light: OKLCH(0.888, 0.044, 285, alpha: 0.22),
            dark: OKLCH(0.345, 0.088, 282, alpha: 0.140),
            lightHC: OKLCH(0.888, 0.044, 285, alpha: 0),
            darkHC: OKLCH(0.345, 0.030, 259, alpha: 0)
        )
        /// **这套没有网格。** 细网格是星云的签名；这里让能量星球独自承担
        /// 「玻璃底下有东西可折射」这件事，不需要再垫一层刻度。
        case .gridLine: Ramp(
            light: OKLCH(0, 0, 0, alpha: 0), dark: OKLCH(0, 0, 0, alpha: 0)
        )
        // MARK: 薄膜
        //
        // **全应用最薄的一档**（浅色 content 0.47，霜白是 0.50，星云是 0.52）。
        // 玻璃形态的重点就在这儿：薄膜越薄，底下那三团颜色透上来得越多，
        // 面板才像「一块玻璃」而不是「一块加了圆角的浅色矩形」。
        // 代价是层与层之间的明度差变小 —— 补偿全在边缘那圈近白的发丝线上。
        /// 悬停。合成后落在 content 和 panel 之间，可点的东西才用。
        case .hover: Ramp(
            light: OKLCH(0.700, 0.040, 255, alpha: 0.09),
            dark: OKLCH(0.995, 0.035, 200, alpha: 0.080),
            lightHC: OKLCH(0.920, 0.008, 255), darkHC: OKLCH(0.315, 0.010, 255)
        )

        // MARK: 边缘、尾光与投影
        //
        // 薄膜薄了，边就得重。这套的边是全应用最亮的一圈 ——
        // 「一块玻璃的厚度全靠它」这句话在这里是字面意思：
        // 拿掉这圈线，面板就真的消失在光晕里了。
        /// 深色那档从 0.30 抬到 0.42。**边是免费的存在感** ——
        /// 它是一条 1px 的线，不进合成链（对比度算的是「文字压在表面上」，
        /// 表面是薄膜叠出来的，边不参与），所以把它加重不用还任何东西。
        /// 薄膜已经薄到全应用最薄，一块面板还立不立得住，全看这条线。
        case .border: Ramp(
            light: OKLCH(0.460, 0.035, 255, alpha: 0.26),
            dark: OKLCH(0.995, 0.035, 200, alpha: 0.42),
            lightHC: OKLCH(0.675, 0.014, 255), darkHC: OKLCH(0.495, 0.014, 255)
        )
        case .borderStrong: Ramp(
            light: OKLCH(0.380, 0.040, 255, alpha: 0.38),
            dark: OKLCH(0.995, 0.040, 200, alpha: 0.56),
            lightHC: OKLCH(0.535, 0.016, 255), darkHC: OKLCH(0.625, 0.016, 255)
        )

        case .ink: Ramp(
            light: OKLCH(0.230, 0.028, 255), dark: OKLCH(0.965, 0.010, 255),
            lightHC: OKLCH(0.150, 0.018, 255), darkHC: OKLCH(1.000, 0.000, 255)
        )
        case .inkSecondary: Ramp(
            light: OKLCH(0.400, 0.028, 255), dark: OKLCH(0.910, 0.014, 255),
            lightHC: OKLCH(0.330, 0.020, 255), darkHC: OKLCH(0.900, 0.010, 255)
        )
        case .inkTertiary: Ramp(
            light: OKLCH(0.500, 0.024, 255), dark: OKLCH(0.805, 0.016, 255),
            lightHC: OKLCH(0.425, 0.018, 255), darkHC: OKLCH(0.815, 0.012, 255)
        )

        // MARK: 电光青（accent）
        /// 焦点环：比 `accent` 亮一档、浓一档。深色档和 accent 同值 ——
        /// 那一档它本来就够亮了，深的是浅色档。
        case .focusRing: Ramp(
            light: OKLCH(0.565, 0.125, 202), dark: OKLCH(0.850, 0.130, 202),
            lightHC: OKLCH(0.385, 0.058, 202), darkHC: OKLCH(0.880, 0.135, 202)
        )
        case .accent: Ramp(
            light: OKLCH(0.470, 0.072, 202), dark: OKLCH(0.850, 0.130, 202),
            lightHC: OKLCH(0.385, 0.058, 202), darkHC: OKLCH(0.880, 0.135, 202)
        )
        /// 实心填充。电光青，chroma 0.121 —— 青在 L 0.790 上的色域上限是 0.135，
        /// 贴着边留了一档余量。
        /// 它现在是**递给系统的那个颜色**（`.tint()` 和玻璃的 tint），字色由系统自己配。
        /// 走深底 + 白字那一版为什么不成，见文件头。
        case .accentFill: Ramp(
            light: OKLCH(0.790, 0.121, 202), dark: OKLCH(0.790, 0.121, 202),
            lightHC: OKLCH(0.820, 0.118, 202), darkHC: OKLCH(0.820, 0.118, 202)
        )
        case .accentSoft: Ramp(
            light: OKLCH(0.870, 0.086, 202, alpha: 0.55),
            dark: OKLCH(0.340, 0.056, 202, alpha: 0.55),
            lightHC: OKLCH(0.940, 0.048, 202), darkHC: OKLCH(0.255, 0.042, 202)
        )
        case .accentSoftBorder: Ramp(
            light: OKLCH(0.790, 0.120, 202, alpha: 0.80),
            dark: OKLCH(0.560, 0.094, 202, alpha: 0.80),
            lightHC: OKLCH(0.730, 0.120, 202), darkHC: OKLCH(0.620, 0.104, 202)
        )
        case .info: Ramp(
            light: OKLCH(0.470, 0.180, 265), dark: OKLCH(0.822, 0.082, 265),
            lightHC: OKLCH(0.382, 0.160, 265), darkHC: OKLCH(0.862, 0.062, 265)
        )
        /// 提示条是通栏的，同样的 chroma 铺满一条会读成「一块蓝色横幅」——
        /// 所以 `infoSoft` 比别的 soft 再低一档。
        case .infoSoft: Ramp(
            light: OKLCH(0.870, 0.058, 265, alpha: 0.55),
            dark: OKLCH(0.340, 0.085, 265, alpha: 0.50),
            lightHC: OKLCH(0.940, 0.026, 265), darkHC: OKLCH(0.258, 0.060, 265)
        )
        case .infoSoftBorder: Ramp(
            light: OKLCH(0.785, 0.100, 265, alpha: 0.80),
            dark: OKLCH(0.492, 0.130, 265, alpha: 0.75),
            lightHC: OKLCH(0.725, 0.115, 265), darkHC: OKLCH(0.555, 0.120, 265)
        )

        case .success: Ramp(
            light: OKLCH(0.478, 0.108, 145), dark: OKLCH(0.840, 0.130, 145),
            lightHC: OKLCH(0.382, 0.098, 145), darkHC: OKLCH(0.868, 0.125, 145)
        )
        case .successSoft: Ramp(
            light: OKLCH(0.878, 0.080, 145, alpha: 0.55),
            dark: OKLCH(0.340, 0.075, 145, alpha: 0.50),
            lightHC: OKLCH(0.944, 0.048, 145), darkHC: OKLCH(0.258, 0.055, 145)
        )
        case .successSoftBorder: Ramp(
            light: OKLCH(0.790, 0.105, 145, alpha: 0.80),
            dark: OKLCH(0.492, 0.100, 145, alpha: 0.75),
            lightHC: OKLCH(0.730, 0.120, 145), darkHC: OKLCH(0.555, 0.105, 145)
        )

        /// 红。浅色那档的 chroma 抬到 0.135（别的主题 0.105）—— 周围全是饱和色，
        /// 一个和邻居一样响的警报等于没有警报。
        ///
        /// **深色那档抬不上去**：红在 L 0.82 上的色域上限只有 0.101，
        /// 而深色外观的正文得亮到 0.82 才够对比度。这不是设计上的取舍，
        /// 是 sRGB 在那个亮度上就没有更红的红了。
        case .danger: Ramp(
            light: OKLCH(0.478, 0.135, 20), dark: OKLCH(0.820, 0.092, 20),
            lightHC: OKLCH(0.385, 0.140, 20), darkHC: OKLCH(0.865, 0.062, 20)
        )
        case .dangerSoft: Ramp(
            light: OKLCH(0.870, 0.062, 20, alpha: 0.55),
            dark: OKLCH(0.338, 0.085, 20, alpha: 0.50),
            lightHC: OKLCH(0.940, 0.026, 20), darkHC: OKLCH(0.262, 0.062, 20)
        )
        case .dangerSoftBorder: Ramp(
            light: OKLCH(0.785, 0.100, 20, alpha: 0.80),
            dark: OKLCH(0.490, 0.105, 20, alpha: 0.75),
            lightHC: OKLCH(0.725, 0.115, 20), darkHC: OKLCH(0.555, 0.110, 20)
        )
        }
    }
}
